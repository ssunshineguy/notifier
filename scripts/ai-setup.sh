#!/usr/bin/env bash
# Installs Notifier rules, skills and guards for Claude Code and Codex.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

python3 - <<'PY'
import json
import os
from pathlib import Path

marker = "# Generated by scripts/ai-setup.sh from ai/agents/."
links = {}
claude_rules = Path(".claude/rules")
claude_agents = Path(".claude/agents")
claude_skills = Path(".claude/skills")
codex_skills = Path(".agents/skills")
codex_agents = Path(".codex/agents")

for directory in (claude_rules, claude_agents, claude_skills, codex_skills, codex_agents):
    for parent in (directory.parent, directory):
        if parent.is_symlink():
            raise SystemExit(f"Refusing to write through {parent}")

for rule in sorted(Path("ai/rules").glob("*.mdc")):
    links[claude_rules / f"{rule.stem}.md"] = rule

agents = sorted(Path("ai/agents").glob("*.md"))
for agent in agents:
    links[claude_agents / agent.name] = agent

for skill in sorted(Path("ai/skills").iterdir()):
    if (skill / "SKILL.md").is_file():
        links[claude_skills / skill.name] = skill
        links[codex_skills / skill.name] = skill

for destination, source in links.items():
    relative = os.path.relpath(source, destination.parent)
    if destination.is_symlink() and os.readlink(destination) == relative:
        continue
    if destination.exists() or destination.is_symlink():
        raise SystemExit(f"Refusing to replace {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.symlink_to(relative)
    print(f"linked {destination} -> {source}")

definitions = set()
for agent in agents:
    opening, _, remainder = agent.read_text().partition("---\n")
    header, separator, instructions = remainder.partition("\n---\n")
    fields = dict(
        line.split(": ", 1) for line in header.splitlines()
        if line.startswith(("name: ", "description: "))
    )
    if opening or not separator or fields.get("name") != agent.stem or not fields.get("description"):
        raise SystemExit(f"Invalid agent front matter in {agent}")
    codex_instructions = (
        "Work read-only. Use only local read and search commands to gather evidence. "
        "Do not edit files, run checks that mutate state, or access external services.\n\n"
        + instructions.strip()
    )
    contents = marker + "\n" + "\n".join(
        f"{key} = {json.dumps(value, ensure_ascii=False)}"
        for key, value in (
            ("name", fields["name"]),
            ("description", fields["description"]),
            ("developer_instructions", codex_instructions),
        )
    ) + "\n"
    destination = codex_agents / f"{agent.stem}.toml"
    definitions.add(destination)
    if destination.is_symlink():
        raise SystemExit(f"Refusing to replace {destination}")
    if destination.exists():
        current = destination.read_text()
        if current == contents:
            continue
        if not current.startswith(marker + "\n"):
            raise SystemExit(f"Refusing to replace {destination}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(contents)
    print(f"generated {destination}")

for directory, source_directory in (
    (claude_rules, Path("../../ai/rules")),
    (claude_agents, Path("../../ai/agents")),
    (claude_skills, Path("../../ai/skills")),
    (codex_skills, Path("../../ai/skills")),
):
    for destination in sorted(directory.glob("*")):
        if destination in links or not destination.is_symlink():
            continue
        if Path(os.readlink(destination)).parent == source_directory:
            destination.unlink()
            print(f"removed {destination}")

for destination in sorted(codex_agents.glob("*.toml")):
    if destination in definitions or destination.is_symlink() or not destination.is_file():
        continue
    with destination.open() as config:
        generated = config.readline().rstrip("\n") == marker
    if generated:
        destination.unlink()
        print(f"removed {destination}")
PY
