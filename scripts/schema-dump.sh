#!/usr/bin/env bash
# Regenerates db/schema/<table>.sql from the local database after migrations.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

out=db/schema
db=(docker compose exec -T postgres)
conn=(-U notifier_migrator -d notifier)

tables="$("${db[@]}" psql "${conn[@]}" -At -c \
  "SELECT tablename FROM pg_tables
   WHERE schemaname = 'notifier' AND tablename <> 'goose_db_version'
   ORDER BY tablename")"

rm -f "$out"/*.sql
for table in $tables; do
  {
    echo "-- Generated by 'make migrate' from db/migrations. Do not edit:"
    echo "-- change the schema with a new migration."
    # \restrict lines carry a random key and would change the files on every run.
    "${db[@]}" pg_dump "${conn[@]}" --schema-only --no-owner --no-privileges \
        --table="notifier.${table}" \
      | grep -v -E '^(SET |SELECT pg_catalog\.|\\restrict|\\unrestrict|--)' \
      | cat -s
  } > "${out}/${table}.sql"
  echo "schema: ${out}/${table}.sql"
done
